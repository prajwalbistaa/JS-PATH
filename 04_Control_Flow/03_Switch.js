// "switch" statement

const month = "3"
switch (month) {
    case "1": // if month is equal to "1", then the code inside this block will be executed.
        console.log("January");
        break;
    case "2": // if month is equal to "2", then the code inside this block will be executed.
        console.log("February");
        break;
    case "3": // if month is equal to "3", then the code inside this block will be executed.
        console.log("March");
        break;
    case "4": // if month is equal to "4", then the code inside this block will be executed.
        console.log("April");
        break;
    case "5": // if month is equal to "5", then the code inside this block will be executed.
        console.log("May");
        break;
    default: // if month is not equal to any of the above cases, then the code inside this block will be executed.
        console.log("Invalid month");
        break;
}